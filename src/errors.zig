pub const AgentError = error{
    InvalidArguments,
    InvalidConfiguration,
    InvalidPath,
    PathOutsideWorkspace,
    FileTooLarge,
    WorkspaceLocked,
    WorkspaceNotInitialized,
    InvalidJson,
    IntegrityFailure,
    InvalidTransition,
    NoRunnableTask,
    ContextBudgetExceeded,
    MissingApiKey,
    ProviderFailure,
    ProviderRateLimited,
    ProviderUnauthorized,
    InvalidLlmResponse,
    ToolDisabled,
    UnknownTool,
    SearchProviderUnavailable,
    ExtractorUnavailable,
    ExtractionFailed,
    DocumentNotFound,
    ExecutionRejected,
    ExecutionTimedOut,
    AcceptanceFailed,
    MaximumStepsReached,
    EvaluationFailed,
};

pub fn message(err: anyerror) []const u8 {
    return switch (err) {
        error.InvalidArguments => "invalid arguments; run with help to inspect the required command syntax",
        error.InvalidConfiguration => "configuration is invalid; validate the JSON values and required fields",
        error.InvalidPath => "path is invalid",
        error.PathOutsideWorkspace => "path resolves outside the workspace",
        error.FileTooLarge => "file exceeds the configured size limit",
        error.WorkspaceLocked => "workspace is locked by another process; remove a stale locks/workspace.lock only after verifying no agent is running",
        error.WorkspaceNotInitialized => "workspace is not initialized; run init first",
        error.InvalidJson => "JSON input is invalid",
        error.IntegrityFailure => "artifact hash verification failed",
        error.InvalidTransition => "requested state transition is invalid",
        error.NoRunnableTask => "the task DAG has no runnable node",
        error.ContextBudgetExceeded => "the bounded context cannot fit the configured byte budget",
        error.MissingApiKey => "the configured LLM API key environment variable is unset",
        error.ProviderFailure => "the external provider request failed; inspect the redacted LLM log and endpoint configuration",
        error.ProviderRateLimited => "the external provider rate limit was reached; retry after the provider reset window",
        error.ProviderUnauthorized => "the external provider rejected credentials; verify the configured API key environment variable",
        error.InvalidLlmResponse => "the LLM returned invalid structured JSON after the bounded repair attempt",
        error.ToolDisabled => "the requested tool is disabled in configuration",
        error.UnknownTool => "the requested tool is not registered",
        error.SearchProviderUnavailable => "no configured search provider is available with valid credentials",
        error.ExtractorUnavailable => "the configured PDF extractor is unavailable; install Poppler pdftotext or correct tools.pdf_extraction_command",
        error.ExtractionFailed => "document text extraction failed; inspect the tool log",
        error.DocumentNotFound => "the requested document index or source was not found",
        error.ExecutionRejected => "code execution was rejected by the sandbox policy",
        error.ExecutionTimedOut => "code execution exceeded the configured timeout",
        error.AcceptanceFailed => "task outputs did not satisfy acceptance checks",
        error.MaximumStepsReached => "scheduler reached max_total_steps before the root task completed",
        error.EvaluationFailed => "evaluation could not be completed from real run artifacts",
        else => @errorName(err),
    };
}
